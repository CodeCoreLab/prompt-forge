//! 构建脚本：把 `web/` 目录下的前端资源以字节数组形式嵌入二进制。
//!
//! 目的：发行产物为**单一可执行文件**（不依赖外部目录），同时保持前端为纯静态资源。
//! 采用生成式 include_bytes 而非引入 `rust-embed` 等额外依赖，编译期开销最低。
//!
//! 生成物：`$OUT_DIR/assets.rs`，导出 `pub static ASSETS: &[(&str, &[u8], &str)]`
//! —— (URL 路径, 字节内容, Content-Type)。

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let web_dir = manifest.join("../../web");
    let web_dir = web_dir.canonicalize().unwrap_or(web_dir);

    println!("cargo:rerun-if-changed={}", web_dir.display());

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let out_file = out_dir.join("assets.rs");

    // 收集 web/ 下所有文件（相对路径 → 绝对路径），BTreeMap 保证生成代码稳定可复现
    let mut files: BTreeMap<String, PathBuf> = BTreeMap::new();
    collect(&web_dir, &web_dir, &mut files);
    files.insert("/index.html".to_string(), web_dir.join("index.html"));

    let mut code = String::new();
    code.push_str("// @generated by build.rs — 前端静态资源内嵌表\n");
    code.push_str("pub static ASSETS: &[(&str, &[u8], &str)] = &[\n");
    for (url, abs) in &files {
        let mime = mime_for(abs);
        code.push_str(&format!(
            "    ({:?}, include_bytes!({:?}), {:?}),\n",
            url,
            abs.to_string_lossy(),
            mime
        ));
    }
    code.push_str("];\n");

    fs::write(&out_file, code).expect("写入 assets.rs 失败");
}

/// 递归收集目录内文件，key 为以 `/` 开头的 URL 路径
fn collect(root: &Path, dir: &Path, out: &mut BTreeMap<String, PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.is_file() {
            let rel = path
                .strip_prefix(root)
                .unwrap_or(&path)
                .to_string_lossy()
                .replace('\\', "/");
            let url = format!("/{rel}");
            out.insert(url, path);
        }
    }
}

/// 极简 Content-Type 映射（只覆盖前端实际使用的扩展名）
fn mime_for(path: &Path) -> &'static str {
    match path
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("")
        .to_ascii_lowercase()
        .as_str()
    {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "txt" | "md" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
